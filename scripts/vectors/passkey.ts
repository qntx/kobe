/// <reference types="node" />
/**
 * Regenerates vectors/passkey.json without importing kernel code: PRF (32 bytes) → entropy =
 * prf[0..16) → BIP-39 mnemonic → seed (PBKDF2-HMAC-SHA512, "mnemonic", 2048, 64) → BIP-32 master →
 * NIP-06 key m/44'/1237'/0'/0/0 (private + x-only public) → walletId.
 *
 * Run from the repo root: bun scripts/vectors/passkey.ts
 */
import { writeFileSync } from "node:fs";

import { schnorr } from "@noble/curves/secp256k1.js";
import { pbkdf2 } from "@noble/hashes/pbkdf2.js";
import { sha256, sha512 } from "@noble/hashes/sha2.js";
import { bytesToHex, concatBytes, utf8ToBytes } from "@noble/hashes/utils.js";
import { HDKey } from "@scure/bip32";
import { entropyToMnemonic } from "@scure/bip39";
import { wordlist } from "@scure/bip39/wordlists/english.js";

const prf = new Uint8Array(32).map((_, i) => i);
const entropy = prf.slice(0, 16);
const mnemonic = entropyToMnemonic(entropy, wordlist);
const seed = pbkdf2(sha512, utf8ToBytes(mnemonic.normalize("NFKD")), utf8ToBytes("mnemonic"), {
  c: 2048,
  dkLen: 64,
});
const master = HDKey.fromMasterSeed(seed);
const node = master.derive("m/44'/1237'/0'/0/0");
const { privateKey } = node;
const { publicKey } = master;
if (
  privateKey === null ||
  privateKey === undefined ||
  publicKey === null ||
  publicKey === undefined
) {
  throw new Error("derivation produced no key");
}
const xonlyPublicKey = schnorr.getPublicKey(privateKey);
const walletId = bytesToHex(
  sha256(concatBytes(utf8ToBytes("qntx-wallet/wallet-id/v1"), publicKey)).slice(0, 8),
);

const out = {
  comment:
    "Passkey wallet vector generated by scripts/vectors/passkey.ts (independent of the kernel): PRF[0..16) → mnemonic → seed → NIP-06 group 0 → walletId.",
  vector: {
    prf: bytesToHex(prf),
    entropy: bytesToHex(entropy),
    mnemonic,
    seed: bytesToHex(seed),
    masterPublicKey: bytesToHex(publicKey),
    groupIndex: 0,
    privateKey: bytesToHex(privateKey),
    publicKey: bytesToHex(xonlyPublicKey),
    walletId,
  },
};

writeFileSync("vectors/passkey.json", `${JSON.stringify(out, null, 2)}\n`);
console.log("wrote vectors/passkey.json", out.vector.walletId);
node.wipePrivateData();
master.wipePrivateData();
