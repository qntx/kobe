/// <reference types="node" />
/**
 * Regenerates vectors/factor-wrap.json without importing kernel code: the factor wrapping format is
 * spelled out byte by byte so this stays an independent implementation of the spec.
 *
 * FactorSk = HKDF-SHA256(ikm = KEK, salt = empty, info = "qntx-wallet/vault/v2/factor-key", 32)
 *
 * FactorPk = X25519(factorSk), stored in the header as base64url (no padding)
 *
 * WrapKey = HKDF-SHA256(ikm = X25519(eph, factorPk), salt = ephPk ‖ factorPk, info =
 * "qntx-wallet/vault/v2/wrap", 32)
 *
 * Binding = HMAC-SHA256(key = DEK, msg = UTF-8("qntx-wallet/vault/v2/binding") ‖ aad)
 *
 * Sealed = 0x02 ‖ ephPk(32) ‖ binding(32) ‖ 0x01 ‖ nonce(24) ‖ XChaCha20-Poly1305(wrapKey, DEK)
 *
 * Aad = 0x01 ‖ u16be(len(UTF-8(context))) ‖ UTF-8(context) ‖ UTF-8(header)
 *
 * Context = "qntx-wallet/vault/v1/factor/" ‖ kind ‖ "/" ‖ id
 *
 * Run from the repo root: bun scripts/vectors/factor-wrap.ts
 */
import { writeFileSync } from "node:fs";

import { xchacha20poly1305 } from "@noble/ciphers/chacha.js";
import { x25519 } from "@noble/curves/ed25519.js";
import { hkdf } from "@noble/hashes/hkdf.js";
import { hmac } from "@noble/hashes/hmac.js";
import { sha256 } from "@noble/hashes/sha2.js";
import { bytesToHex, concatBytes, hexToBytes, utf8ToBytes } from "@noble/hashes/utils.js";
import { base64urlnopad } from "@scure/base";

const FACTOR_KEY_INFO = utf8ToBytes("qntx-wallet/vault/v2/factor-key");
const WRAP_INFO = utf8ToBytes("qntx-wallet/vault/v2/wrap");
const BINDING_TAG = utf8ToBytes("qntx-wallet/vault/v2/binding");

function aad(context: string, header: string): Uint8Array {
  const c = utf8ToBytes(context);
  const h = utf8ToBytes(header);
  const out = new Uint8Array(3 + c.length + h.length);
  out[0] = 0x01;
  new DataView(out.buffer).setUint16(1, c.length);
  out.set(c, 3);
  out.set(h, 3 + c.length);
  return out;
}

function wrap(
  dek: Uint8Array,
  eph: Uint8Array,
  nonce: Uint8Array,
  kind: string,
  id: string,
  header: string,
  factorPk: Uint8Array,
): { publicKey: string; binding: string; sealed: string } {
  const ephPk = x25519.getPublicKey(eph);
  const shared = x25519.getSharedSecret(eph, factorPk);
  const wrapKey = hkdf(sha256, shared, concatBytes(ephPk, factorPk), WRAP_INFO, 32);
  const context = `qntx-wallet/vault/v1/factor/${kind}/${id}`;
  const envelope = concatBytes(
    new Uint8Array([0x01]),
    nonce,
    xchacha20poly1305(wrapKey, nonce, aad(context, header)).encrypt(dek),
  );
  const binding = hmac(sha256, dek, concatBytes(BINDING_TAG, aad(context, header)));
  return {
    publicKey: base64urlnopad.encode(factorPk),
    binding: bytesToHex(binding),
    sealed: bytesToHex(concatBytes(new Uint8Array([0x02]), ephPk, binding, envelope)),
  };
}

const dek = "0f1e2d3c4b5a69788796a5b4c3d2e1f00f1e2d3c4b5a69788796a5b4c3d2e1f0";

const cases = [
  {
    name: "password",
    kek: "d43390937c8e83be3b33e1fb9596ddf65cec5880a09786837bde9847aadba95e",
    eph: "404142434445464748494a4b4c4d4e4f505152535455565758595a5b5c5d5e5f",
    nonce: "c0c1c2c3c4c5c6c7c8c9cacbcccdcecfd0d1d2d3d4d5d6d7",
    kind: "password",
    id: "00112233445566778899aabbccddeeff",
    createdAt: 1767225600000,
  },
  {
    name: "passkey",
    kek: "73d54cc06736091b03f0af42309d81668739b50d65549a6eb6b2a65c419392ca",
    eph: "808182838485868788898a8b8c8d8e8f909192939495969798999a9b9c9d9e9f",
    nonce: "e0e1e2e3e4e5e6e7e8e9eaebecedeeeff0f1f2f3f4f5f6f7",
    kind: "passkey",
    id: "ffeeddccbbaa99887766554433221100",
    createdAt: 1767225600000,
  },
];

const vectors = [];
for (const c of cases) {
  const factorSk = hkdf(sha256, hexToBytes(c.kek), new Uint8Array(0), FACTOR_KEY_INFO, 32);
  const factorPk = x25519.getPublicKey(factorSk);
  const publicKey = base64urlnopad.encode(factorPk);
  const header =
    c.kind === "password"
      ? JSON.stringify({
          salt: "ABEiM0RVZneImaq7zN3u_w",
          iterations: 600000,
          publicKey,
          createdAt: c.createdAt,
        })
      : JSON.stringify({
          credentialId: "3q2-78r-",
          publicKey,
          createdAt: c.createdAt,
        });
  vectors.push({
    name: c.name,
    kek: c.kek,
    dek,
    eph: c.eph,
    nonce: c.nonce,
    kind: c.kind,
    id: c.id,
    header,
    ...wrap(
      hexToBytes(dek),
      hexToBytes(c.eph),
      hexToBytes(c.nonce),
      c.kind,
      c.id,
      header,
      factorPk,
    ),
  });
}

const out = {
  comment: [
    "Factor wrap v2 vectors generated by scripts/vectors/factor-wrap.ts (independent of the kernel).",
    "factorSk = HKDF-SHA256(kek, '', 'qntx-wallet/vault/v2/factor-key'); publicKey = X25519(factorSk);",
    "sealed = 0x02 || ephPk(32) || binding(32) || envelopeV1Seal(wrapKey, dek);",
    "wrapKey = HKDF-SHA256(X25519(eph, factorPk), ephPk||factorPk, 'qntx-wallet/vault/v2/wrap');",
    "binding = HMAC-SHA256(dek, 'qntx-wallet/vault/v2/binding' || aad).",
  ].join(" "),
  vectors,
};

writeFileSync("vectors/factor-wrap.json", `${JSON.stringify(out, null, 2)}\n`);
console.log("wrote vectors/factor-wrap.json");
