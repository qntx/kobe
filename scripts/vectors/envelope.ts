/**
 * Regenerates vectors/envelope.json without importing kernel code: the envelope format is spelled
 * out byte by byte so this stays an independent implementation of the spec.
 *
 * Sealed = 0x01 ‖ nonce(24) ‖ XChaCha20-Poly1305(key, nonce, plaintext, aad)
 *
 * Aad = 0x01 ‖ u16be(len(UTF-8(context))) ‖ UTF-8(context) ‖ UTF-8(header)
 *
 * Run from the repo root: bun scripts/vectors/envelope.ts
 */
import { writeFileSync } from "node:fs";

import { xchacha20poly1305 } from "@noble/ciphers/chacha.js";
import { bytesToHex, concatBytes, hexToBytes, utf8ToBytes } from "@noble/hashes/utils.js";

function aad(context: string, header: string): Uint8Array {
  const c = utf8ToBytes(context);
  const h = utf8ToBytes(header);
  const out = new Uint8Array(3 + c.length + h.length);
  out[0] = 0x01;
  new DataView(out.buffer).setUint16(1, c.length);
  out.set(c, 3);
  out.set(h, 3 + c.length);
  return out;
}

function vector(
  key: Uint8Array,
  nonce: Uint8Array,
  context: string,
  header: string,
  plaintext: Uint8Array,
): { sealed: string } {
  const sealed = concatBytes(
    new Uint8Array([0x01]),
    nonce,
    xchacha20poly1305(key, nonce, aad(context, header)).encrypt(plaintext),
  );
  return { sealed: bytesToHex(sealed) };
}

